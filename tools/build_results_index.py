"""Collect every methods/*/experiments/*/results/summary.csv into RESULTS.md.

usage: python tools/build_results_index.py
"""
import csv, glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

rows = []
for path in sorted(glob.glob(os.path.join(ROOT, 'methods/*/experiments/*/results/summary.csv'))):
    exp = os.path.relpath(os.path.dirname(os.path.dirname(path)), ROOT)
    with open(path, newline='') as f:
        rows += [dict(r, experiment=exp) for r in csv.DictReader(f)]


def num(x):
    return f'{float(x):.4f}' if x not in ('', None) else ''


def ours(r):
    s = num(r['ours_mean'])
    if r['ours_std']:
        s += f" ± {num(r['ours_std'])}"
    return f"{s} (n={r['n_runs']})"


def delta(r):
    return f"{float(r['ours_mean']) - float(r['paper_mean']):+.4f}" if r['paper_mean'] else ''


def paper(r):
    s = num(r['paper_mean'])
    if r['paper_std']:
        s += f" ± {num(r['paper_std'])}"
    return f"{s} ({r['paper_source']})" if s else '–'


def link(exp):
    return f'[{os.path.basename(exp)}]({exp})'


def table(rs):
    out = ['| Method | Dataset | Protocol | Setting | Metric | Paper | Reproduced | Δ | Experiment |',
           '|---|---|---|---|---|---|---|---|---|']
    out += [f"| {r['method']} | {r['dataset']} | {r['protocol']} | {r['setting']} | {r['metric']} | {paper(r)} "
            f"| {ours(r)} | {delta(r)} | {link(r['experiment'])} |" for r in rs]
    return out


methods = sorted({r['method'] for r in rows})
datasets = sorted({r['dataset'] for r in rows})
lines = ['# Results index', '',
         '<!-- Generated by `python tools/build_results_index.py`; edit the experiments\' summary.csv, not this file. -->',
         '',
         'Every number links back to the experiment that produced it. Δ is reproduced − paper. Results are only',
         'comparable across methods when the protocol (subject split) matches.', '',
         '## Coverage', '',
         '| Method | ' + ' | '.join(datasets) + ' |', '|---|' + '---|' * len(datasets)]
for m in methods:
    cells = []
    for d in datasets:
        exps = list(dict.fromkeys(r['experiment'] for r in rows if r['method'] == m and r['dataset'] == d))
        cells.append('<br>'.join(link(e) for e in exps))
    lines.append(f'| {m} | ' + ' | '.join(cells) + ' |')
headline = sorted((r for r in rows if r['headline'] == '1'), key=lambda r: (r['dataset'], r['method']))
lines += ['', '## Headline numbers', ''] + table(headline)
lines += ['', '## All reported numbers', '', '<details><summary>Expand</summary>', ''] + table(rows)
lines += ['', '</details>', '']

with open(os.path.join(ROOT, 'RESULTS.md'), 'w') as f:
    f.write('\n'.join(lines))
print(f'wrote RESULTS.md ({len(rows)} rows from {len({r["experiment"] for r in rows})} experiments)')
